"""Public security service contracts."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol, runtime_checkable

from app.security.models import AuthUserRecord, RoleSummary, UserIdentity, UserSession, UserSummary


class AuthenticationService(Protocol):
    def setup_initial_administrator(
        self, username: str, display_name: str, password: str
    ) -> UserIdentity: ...
    def authenticate(self, username: str, password: str) -> UserIdentity: ...


class UserAdministrationService(Protocol):
    def create_user(
        self, actor_id: str, username: str, display_name: str, password: str, role_ids: tuple[str, ...]
    ) -> UserIdentity: ...
    def get_user_role_ids(self, actor_id: str, user_id: str) -> tuple[str, ...]: ...
    def update_user_roles(self, actor_id: str, user_id: str, role_ids: tuple[str, ...]) -> None: ...
    def set_user_active(self, actor_id: str, user_id: str, is_active: bool) -> None: ...
    def list_users(self, actor_id: str) -> tuple[UserSummary, ...]: ...
    def list_roles(self, actor_id: str) -> tuple[RoleSummary, ...]: ...


@runtime_checkable
class AuthorizationService(Protocol):
    def require(self, actor_id: str, permission: str, resource: object | None = None) -> None: ...
    def is_allowed(self, actor_id: str, permission: str, resource: object | None = None) -> bool: ...


class SessionService(Protocol):
    def has_active_user_session(self, user_id: str) -> bool: ...
    def create(self, identity: UserIdentity) -> UserSession: ...
    def get(self, session_id: str) -> UserSession | None: ...
    def revoke(self, session_id: str) -> None: ...


class UserRepository(Protocol):
    def has_users(self) -> bool: ...
    def create_initial_admin(self, username: str, display_name: str, password_hash: str) -> UserIdentity: ...
    def create_user(self, username: str, display_name: str, password_hash: str, role_ids: tuple[str, ...]) -> UserIdentity: ...
    def get_auth_record(self, username: str) -> AuthUserRecord | None: ...
    def get_identity(self, user_id: str) -> UserIdentity | None: ...
    def user_has_permission(self, user_id: str, permission: str) -> bool: ...
    def record_failed_login(self, user_id: str | None, *, locked_until: datetime | None) -> None: ...
    def reset_login_failures(self, user_id: str) -> None: ...
    def audit(self, *, actor_id: str | None, action: str, target_user_id: str | None,
              outcome: str, error_code: str | None = None, details: dict[str, object] | None = None) -> None: ...
    def list_users(self) -> tuple[UserSummary, ...]: ...
    def list_roles(self) -> tuple[RoleSummary, ...]: ...
    def get_user_role_ids(self, user_id: str) -> tuple[str, ...]: ...
    def update_user_roles(self, user_id: str, role_ids: tuple[str, ...]) -> None: ...
    def set_user_active(self, user_id: str, is_active: bool) -> None: ...
    def has_global_admin_permission(self, user_id: str) -> bool: ...
    def count_active_global_administrators(self) -> int: ...
    def role_ids_have_global_permission(self, role_ids: tuple[str, ...]) -> bool: ...
