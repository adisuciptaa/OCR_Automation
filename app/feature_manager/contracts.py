"""Public contracts required by Feature Manager implementations."""
from __future__ import annotations

from collections.abc import Mapping
from typing import Protocol
from pathlib import Path

from app.feature_manager.models import (
    ConfigurationScope, FeatureConfiguration, FeatureConfigurationSchema, FeatureDescriptor, FeatureRecord, PackageCandidate,
    PackageValidationResult, FeatureHealthReport, PublisherRecord, PublisherKeyRecord,
)
from app.security.contracts import AuthorizationService


class FeatureRegistryRepository(Protocol):
    def get(self, feature_id: str) -> FeatureRecord | None: ...
    def list_all(self) -> tuple[FeatureRecord, ...]: ...
    def save(self, record: FeatureRecord) -> None: ...
    def delete(self, feature_id: str) -> None: ...
    def audit(self, *, actor_id: str, feature_id: str, operation: str, previous_state: str | None,
              resulting_state: str | None, package_digest: str | None, result: str,
              error_code: str | None = None) -> None: ...


class FeatureManager(Protocol):
    def install_archive(self, archive_path: str, actor_id: str) -> FeatureRecord: ...
    def discover(self) -> tuple[PackageCandidate, ...]: ...
    def validate(self, candidate: PackageCandidate) -> PackageValidationResult: ...
    def register(self, candidate: PackageCandidate, actor_id: str) -> FeatureRecord: ...
    def enable(self, feature_id: str, actor_id: str) -> FeatureRecord: ...
    def disable(self, feature_id: str, actor_id: str) -> FeatureRecord: ...
    def update(self, feature_id: str, package_path: str, actor_id: str) -> FeatureRecord: ...
    def uninstall(self, feature_id: str, actor_id: str) -> FeatureRecord: ...
    def list_available(self, user_id: str) -> tuple[FeatureDescriptor, ...]: ...
    def get_enabled_feature(self, feature_id: str, user_id: str) -> FeatureRecord: ...


class FeatureConfigurationRepository(Protocol):
    def get(self, feature_id: str, scope: ConfigurationScope, scope_key: str) -> FeatureConfiguration | None: ...
    def save(self, configuration: FeatureConfiguration) -> None: ...
    def delete(self, feature_id: str, scope: ConfigurationScope, scope_key: str) -> None: ...
    def list_for_feature(self, feature_id: str) -> tuple[FeatureConfiguration, ...]: ...
    def migrate_profiles(self, feature_id: str, updates: list[tuple[ConfigurationScope, str, int, dict[str, object]]], actor_id: str) -> None: ...


class FeatureConfigurationManager(Protocol):
    def get_configuration_schema(self, feature_id: str, actor_id: str) -> FeatureConfigurationSchema: ...
    def get_configuration(self, feature_id: str, actor_id: str, scope: ConfigurationScope,
                          scope_key: str) -> FeatureConfiguration: ...
    def save_configuration(self, feature_id: str, actor_id: str, scope: ConfigurationScope,
                           scope_key: str, values: Mapping[str, object]) -> FeatureConfiguration: ...
    def reset_configuration(self, feature_id: str, actor_id: str, scope: ConfigurationScope,
                            scope_key: str) -> FeatureConfiguration: ...


class FeatureDataMigrationEngine(Protocol):
    def migrate_configuration_profiles(self, *, feature_id: str, actor_id: str,
                                       package_root: Path, target_version: int) -> int: ...
    def migrate_feature_data(self, *, feature_id: str, actor_id: str, package_root: Path,
                             from_version: int, to_version: int) -> Path: ...


class FeatureHealthCheckService(Protocol):
    def check_feature(self, feature_id: str, actor_id: str) -> FeatureHealthReport: ...


class FeatureRollbackService(Protocol):
    def create_checkpoint(self, feature_id: str, actor_id: str) -> str: ...
    def complete_checkpoint(self, checkpoint_id: str, actor_id: str) -> None: ...
    def rollback(self, checkpoint_id: str, actor_id: str) -> FeatureRecord: ...
    def recover_pending(self) -> tuple[str, ...]: ...


class PublisherTrustService(Protocol):
    def register_publisher(self, publisher_id: str, display_name: str,
                           public_key_b64: str, actor_id: str) -> PublisherRecord: ...
    def add_public_key(self, publisher_id: str, public_key_b64: str, actor_id: str) -> PublisherKeyRecord: ...
    def revoke_key(self, publisher_id: str, key_id: str, actor_id: str) -> None: ...
    def revoke_publisher(self, publisher_id: str, actor_id: str) -> None: ...
    def list_publishers(self, actor_id: str) -> tuple[PublisherRecord, ...]: ...
    def list_keys(self, publisher_id: str, actor_id: str) -> tuple[PublisherKeyRecord, ...]: ...
    def verify_package(self, feature_id: str, package_root: Path) -> str: ...
